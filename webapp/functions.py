import json
from psycopg2 import connect

def build_prompt(query, tables):
    """Function to generate a prompt to instruct the agent to create a sql query"""
    prompt = f"""
Generate a SQL query to answer the following question from the user:
\"{query}\"

The SQL query should use only tables with the following SQL definitions:

"""

    for idx, table in enumerate(tables):
        prompt += f"""Table {idx+1}:\n{table}\n\n"""

    output_format = """Make sure you ONLY output an SQL query and no explanation."""

    prompt += output_format

    return prompt

def get_connection_details(connection_file, source_name):
    """Function to read postgres db connection details from file"""
    try:
        with open(connection_file, 'r') as fh:
            data = json.load(fh)
    except Exception as e:
        import os
        dirs = os.listdir(os.getcwd())
        raise Exception(f"The file {connection_file} not in the folder. The following files are present:\n{dirs}")

    for source in data["sources"]:
        if source["source_name"] == source_name:
            return source["host"], source["port"], source["dbname"], source["user"], source["password"]

def run_query(query, host, port, dbname, user, password):
    """Function running a query on the database"""
    conn = connect(
        host=host,
        port=port,
        dbname=dbname,
        user=user,
        password=password
    )

    cur = conn.cursor()

    res = cur.execute(query)

    return cur.fetchall()

