def convert_dtype(lst:list)-> list:
    result = list()
    for row in lst:
        col = tuple()
        for col_value in row:
            if isinstance(col_value, Decimal):
                col += (float(col_value),)
            else:
                col += (col_value,)
        result.append(col)
    return result



